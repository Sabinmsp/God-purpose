export const FONT_CHARS = Object.keys(GLYPHS).join("");
export const FONT_CELL = { w: 7, h: 9 };

export function buildFont(): Pixels {
  const chars = FONT_CHARS;
  const p = new Pixels(chars.length * FONT_CELL.w, FONT_CELL.h);
  const cell = new Pixels(FONT_CELL.w, FONT_CELL.h);
  [...chars].forEach((ch, i) => {
    cell.buf.fill(0);
    const g = GLYPHS[ch].padEnd(35, ".");
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (g[y * 5 + x] === "#") cell.set(x + 1, y + 1, "#ffffff");
    cell.outline("#1b1424");
    p.blit(cell, i * FONT_CELL.w, 0);
  });
  return p;
}
